const router = require('express').Router();
const auth  = require('../controllers/auth/citizenAuth');
const app   = require('../controllers/citizen/applicationController');
const sup   = require('../controllers/citizen/supportController');
const notif = require('../controllers/notificationController');
const reports = require('../controllers/reportsController');
const { verifyToken, authorize } = require('../middlewares/auth');
const { uploadPhoto, uploadDocuments } = require('../middlewares/upload');
const C = [verifyToken, authorize('citizen')];

router.post('/register', uploadPhoto.single('photo'), auth.register);
router.post('/login', auth.login);
router.get('/profile', ...C, auth.getProfile);
router.put('/profile', ...C, uploadPhoto.single('photo'), auth.updateProfile);
router.put('/change-password', ...C, auth.changePassword);
router.get('/dashboard', ...C, app.getDashboardStats);
router.get('/reports', ...C, reports.citizenReports);
router.post('/applications', ...C, uploadDocuments.array('documents', 10), app.applyForCertificate);
router.get('/applications', ...C, app.getMyApplications);
router.get('/applications/track/:application_number', ...C, app.trackApplication);
router.get('/applications/:id', ...C, app.getApplicationDetail);
router.put('/applications/:id/cancel', ...C, app.cancelApplication);
router.put('/applications/:id/resubmit', ...C, app.resubmitApplication);
router.get('/applications/:id/download', ...C, app.downloadCertificate);
router.get('/notifications', ...C, notif.getNotifications);
router.put('/notifications/read-all', ...C, notif.markAllAsRead);
router.put('/notifications/:id/read', ...C, notif.markAsRead);
router.post('/support', ...C, sup.raiseTicket);
router.get('/support', ...C, sup.getMyTickets);
module.exports = router;